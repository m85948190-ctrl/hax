(()=>{
  const clean=v=>String(v??'').trim();
  const state=()=>window.HAxBROKai51Bootstrap?.state?.()||{};
  async function unified(prompt,history=[],hooks={}){
    const fn=window.HAxBROKai51Bootstrap?.unifiedGenerate;
    if(!fn) throw new Error('KAI 51 unified runtime is not loaded');
    return fn(clean(prompt),history,hooks);
  }
  function stripCode(text){
    const s=clean(text);
    const m=s.match(/```(?:html)?\s*([\s\S]*?)```/i);
    return (m?m[1]:s).replace(/^html\s*/i,'').trim();
  }
  async function appMaker(prompt,history=[],hooks={},options={}){
    const q=clean(prompt); if(!q) throw new Error('Describe the application to build.');
    const existing=options?.existing&&Array.isArray(options.existing.files)?options.existing:null;
    const existingFiles=existing?existing.files.map(f=>'FILE: '+String(f.path||'index.html')+'\n'+String(f.content||'').slice(0,6000)).join('\n\n').slice(0,16000):'';
    const requestContext=existing
      ? q+'\n\nEXISTING APPLICATION — preserve its identity and working features; apply only the requested change.\nAPP NAME: '+String(existing.name||'Existing app')+'\nAPP SUMMARY: '+String(existing.summary||'')+'\n'+existingFiles
      : q;
    const nativeFallback=async(reason)=>{
      hooks.onStage?.('repair','KAI 51 · native recovery · producing a usable preview artifact');
      const appName=existing?.name||(q.match(/\b(?:called|named|titled|name it|call it)\s+["']?([^"'\n,.!?]{1,60})/i)||[])[1]?.trim()||'';
      const r=await fetch('/api/appmaker-original-generate',{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify({prompt:q,appName,existing})});
      const d=await r.json().catch(()=>({}));
      if(!r.ok||!d.ok||!Array.isArray(d.files)||!d.files.some(f=>f?.content)) throw new Error(d.error||d.recoveryError||'Native App Maker recovery failed');
      hooks.onStage?.('composing','KAI 51 · native recovery artifact ready');
      return {...d,lane:'local-native-recovery',fallback:true,recoveryReason:String(reason||'Neural build unavailable')};
    };
    hooks.onStage?.('understanding','KAI 51 · LOCAL · understanding the product intent');
    let local=null;
    try{local=await unified('APP MAKER ANALYSIS ONLY. Do not generate code yet. Analyze the requested product or modification, infer product type, user flow, interactions, state, responsive requirements and failure cases. Return a concise implementation brief.\n\nREQUEST:\n'+requestContext,history,{onStage:hooks.onStage,onHandoff:()=>{}})}catch(e){local={error:e?.message||String(e)}}
    const brief=local?.response||local?.reason||'';
    hooks.onStage?.('github','KAI 51 · GITHUB · generating the application artifact');
    try{
      const generationPrompt='You are the KAI 51 application build lane. Generate the COMPLETE requested application as one self-contained HTML document. Return ONLY HTML beginning with <!doctype html>, with inline CSS and JavaScript. It must be a real working app, not a mockup. For modifications, preserve the existing app identity and every working feature; change only what was requested. Include visible states and error handling. Make it responsive on phone and desktop.\n\nUSER REQUEST AND EXISTING APP CONTEXT:\n'+requestContext+'\n\nLOCAL KAI 51 IMPLEMENTATION BRIEF:\n'+brief.slice(0,5000);
      const github=await window.HAxBROKai51Bootstrap?.generate?.(generationPrompt,history,{onStage:hooks.onStage},'github');
      if(!github?.response) throw new Error('KAI 51 GITHUB did not return an application artifact');
      let html=stripCode(github.response);
      if(!/^<!doctype html>/i.test(html)){const start=html.search(/<!doctype html>/i);if(start>=0)html=html.slice(start);}
      if(!/^<!doctype html>/i.test(html)) throw new Error('KAI 51 GITHUB returned text instead of a complete HTML artifact');
      hooks.onStage?.('composing','KAI 51 · combined LOCAL + GITHUB build verified');
      return {lane:'github',combined:true,localAnalysis:brief,github,response:html,files:[{path:'index.html',content:html}],name:existing?.name||q.slice(0,70),summary:existing?.summary||'Application generated by the combined KAI 51 LOCAL analysis + GITHUB neural build lane.'};
    }catch(e){return nativeFallback(e?.message||String(e))}
  }
  async function workspace(prompt,history=[],hooks={}){return unified(prompt,history,hooks)}
  window.HAxBROKaiCapabilityBridge={version:'v1-local-github',state,unified,appMaker,workspace};
})();