(()=>{
  const clean=v=>String(v??'').trim();
  const state=()=>window.HAxBROKai51Bootstrap?.state?.()||{};
  async function unified(prompt,history=[],hooks={}){
    const fn=window.HAxBROKai51Bootstrap?.unifiedGenerate;
    if(!fn) throw new Error('KAI 51 unified runtime is not loaded');
    return fn(clean(prompt),history,hooks);
  }
  function stripCode(text){
    const s=clean(text);
    const m=s.match(/```(?:html)?\s*([\s\S]*?)```/i);
    return (m?m[1]:s).replace(/^html\s*/i,'').trim();
  }
  async function appMaker(prompt,history=[],hooks={}){
    const q=clean(prompt); if(!q) throw new Error('Describe the application to build.');
    hooks.onStage?.('understanding','KAI 51 · LOCAL · understanding the product intent');
    let local=null;
    try{local=await unified('APP MAKER ANALYSIS ONLY. Do not generate code yet. Analyze this application request, infer the product type, core user flow, required screens, interactions, data/state needs, responsive requirements, and likely failure cases. Return a concise implementation brief for the build lane.\n\nREQUEST:\n'+q,history,{onStage:hooks.onStage,onHandoff:()=>{}})}catch(e){local={error:e?.message||String(e)}}
    const brief=local?.response||local?.reason||'';
    hooks.onStage?.('github','KAI 51 · GITHUB · generating the application artifact');
    const generationPrompt='You are the KAI 51 application build lane. Generate the COMPLETE application requested below as one self-contained HTML document. Return ONLY the HTML document, beginning with <!doctype html>. Use inline CSS and JavaScript only. No markdown fences. It must be a real working app, not a mockup or explanation. Preserve the requested product identity and implement the primary interaction end-to-end with visible states and error handling. Make it responsive on phone and desktop.\n\nUSER REQUEST:\n'+q+'\n\nLOCAL KAI 51 IMPLEMENTATION BRIEF:\n'+brief.slice(0,10000);
    const github=await window.HAxBROKai51Bootstrap?.generate?.(generationPrompt,history);
    if(!github?.response) throw new Error('KAI 51 GITHUB did not return an application artifact');
    let html=stripCode(github.response);
    if(!/^<!doctype html>/i.test(html)){const start=html.search(/<!doctype html>/i);if(start>=0)html=html.slice(start);}
    if(!/^<!doctype html>/i.test(html)) throw new Error('KAI 51 GITHUB returned text instead of a complete HTML artifact');
    hooks.onStage?.('composing','KAI 51 · combined LOCAL + GITHUB build verified');
    return {lane:'github',combined:true,localAnalysis:brief,github, response:html,files:[{path:'index.html',content:html}],name:q.slice(0,70),summary:'Application generated by the combined KAI 51 LOCAL analysis + GITHUB neural build lane.'};
  }
  async function workspace(prompt,history=[],hooks={}){return unified(prompt,history,hooks)}
  window.HAxBROKaiCapabilityBridge={version:'v1-local-github',state,unified,appMaker,workspace};
})();